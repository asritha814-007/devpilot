def get_rule_explanation(finding: Dict[str, Any]) -> Dict[str, Any]:
    """Provide structured explanation from internal rule base."""
    rule_id = finding.get("rule_id", "")
    kb = RULE_KNOWLEDGE_BASE.get(rule_id, {
        "summary": finding.get("description", "Potential code quality or logic issue detected."),
        "why_it_happened": "The code triggered a static analysis diagnostic check.",
        "how_to_fix": finding.get("suggested_action", "Review the highlighted code segment."),
        "beginner_tip": "Read the error message carefully and test small parts of your code in isolation."
    })

    return {
        "issue_id": finding.get("id"),
        "summary": kb["summary"],
        "why_it_happened": kb["why_it_happened"],
        "how_to_fix": kb["how_to_fix"],
        "beginner_tip": kb["beginner_tip"],
        "provider": "DevPilot Rule-Based Engine (Offline - No AI API key configured)",
        "is_ai_generated": False
    }


async def generate_explanations(
    code: str,
    findings: List[Dict[str, Any]]
) -> List[Dict[str, Any]]:
    """
    Generate beginner-friendly explanations.
    Uses Gemini API or OpenAI API if configured in environment, otherwise returns rule explanations.
    """
    if not findings:
        return []

    gemini_key = os.environ.get("GEMINI_API_KEY", "").strip()
    openai_key = os.environ.get("OPENAI_API_KEY", "").strip()

    # Attempt Real Gemini Call if key is present
    if gemini_key:
        try:
            explanations = await _call_gemini_api(code, findings, gemini_key)
            if explanations:
                return explanations
        except Exception as exc:
            logger.warning(f"Gemini API call failed: {exc}. Falling back to rule-based engine.")

    # Attempt Real OpenAI Call if key is present
    if openai_key:
        try:
            explanations = await _call_openai_api(code, findings, openai_key)
            if explanations:
                return explanations
        except Exception as exc:
            logger.warning(f"OpenAI API call failed: {exc}. Falling back to rule-based engine.")

    # Honest, reliable fallback: Rule-based engine
    return [get_rule_explanation(f) for f in findings]


async def _call_gemini_api(
    code: str,
    findings: List[Dict[str, Any]],
    api_key: str
) -> Optional[List[Dict[str, Any]]]:
    """Call Google Gemini REST API."""
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={api_key}"
    
    prompt = f"""
You are DevPilot, an expert AI Python tutor. Explain the following issues detected in this Python code.
Write in clear, beginner-friendly language without jargon.

Source Code:
```python
{code}
```

Detected Issues:
{json.dumps([{'id': f['id'], 'title': f['title'], 'rule': f['rule_id'], 'line': f.get('line'), 'col': f.get('col')} for f in findings], indent=2)}

Return ONLY a valid JSON array of objects matching this exact structure:
[
  {{
    "issue_id": "<id matching the issue>",
    "summary": "<plain English summary of what is wrong>",
    "why_it_happened": "<why this occurs in Python>",
    "how_to_fix": "<concrete step-by-step instructions to fix it>",
    "beginner_tip": "<a friendly takeaway or memory tip>"
  }}
]
Do not wrap in markdown tags if possible, or use standard ```json.
"""

    payload = {
        "contents": [{
            "parts": [{"text": prompt}]
        }],
        "generationConfig": {
            "temperature": 0.2,
            "responseMimeType": "application/json"
        }
    }

    async with httpx.AsyncClient(timeout=15.0) as client:
        res = await client.post(url, json=payload)
        if res.status_code == 200:
            data = res.json()
            candidates = data.get("candidates", [])
            if candidates:
                raw_text = candidates[0].get("content", {}).get("parts", [{}])[0].get("text", "")
                parsed = json.loads(raw_text)
                if isinstance(parsed, list):
                    for item in parsed:
                        item["provider"] = "Google Gemini 1.5 Flash (AI Generated)"
                        item["is_ai_generated"] = True
                    return parsed
    return None


async def _call_openai_api(
    code: str,
    findings: List[Dict[str, Any]],
    api_key: str
) -> Optional[List[Dict[str, Any]]]:
    """Call OpenAI compatible REST API."""
    url = "https://api.openai.com/v1/chat/completions"
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json"
    }
    prompt = f"""
Explain the following detected issues in this Python code for a beginner student.
Code:
{code}

Findings:
{json.dumps(findings, indent=2)}

Return a JSON array of objects with keys: issue_id, summary, why_it_happened, how_to_fix, beginner_tip.
"""
    payload = {
        "model": "gpt-4o-mini",
        "messages": [
            {"role": "system", "content": "You are DevPilot. Always respond with valid JSON array."},
            {"role": "user", "content": prompt}
        ],
        "temperature": 0.2,
        "response_format": {"type": "json_object"}
    }

    async with httpx.AsyncClient(timeout=15.0) as client:
        res = await client.post(url, headers=headers, json=payload)
        if res.status_code == 200:
            data = res.json()
            content = data["choices"][0]["message"]["content"]
            parsed = json.loads(content)
            items = parsed.get("explanations") if isinstance(parsed, dict) else parsed
            if isinstance(items, list):
                for item in items:
                    item["provider"] = "OpenAI GPT-4o-mini (AI Generated)"
                    item["is_ai_generated"] = True
                return items
    return None
